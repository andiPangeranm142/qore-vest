// Build contracts/CrossVmCaller.artifact.ts from solc output (research probe).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dir, "..");
const abi = JSON.parse(fs.readFileSync(path.join(root, "out", "contracts_CrossVmCaller_sol_CrossVmCaller.abi"), "utf8"));
const bin = fs.readFileSync(path.join(root, "out", "contracts_CrossVmCaller_sol_CrossVmCaller.bin"), "utf8").trim();
const body = `// AUTO-GENERATED by scripts/build-caller-artifact.mjs from contracts/CrossVmCaller.sol\n// (solc 0.8.24, --optimize). Do not edit by hand.\n`
  + `export const crossVmCallerAbi = ${JSON.stringify(abi, null, 2)} as const;\n\nexport const crossVmCallerBytecode = "0x${bin}" as const;\n`;
fs.writeFileSync(path.join(root, "contracts", "CrossVmCaller.artifact.ts"), body);
console.log(`Wrote CrossVmCaller.artifact.ts (${abi.length} ABI entries, ${bin.length / 2} bytes).`);
