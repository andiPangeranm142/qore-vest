// Regenerate contracts/*.artifact.ts from solc output in out/.
// Run after editing contracts/*.sol: npm run compile
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dir, "..");
function build(name, varPrefix) {
  const abi = JSON.parse(fs.readFileSync(path.join(root, "out", `contracts_${name}_sol_${name}.abi`), "utf8"));
  const bin = fs.readFileSync(path.join(root, "out", `contracts_${name}_sol_${name}.bin`), "utf8").trim();
  if (!/^[0-9a-fA-F]+$/.test(bin) || bin.length === 0) throw new Error(`Unexpected bytecode for ${name}.`);
  const body = `// AUTO-GENERATED by scripts/build-artifact.mjs from contracts/${name}.sol\n// (solc 0.8.24, --optimize). Do not edit by hand; run \`npm run compile\`.\n`
    + `export const ${varPrefix}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\nexport const ${varPrefix}Bytecode = "0x${bin}" as const;\n`;
  fs.writeFileSync(path.join(root, "contracts", `${name}.artifact.ts`), body);
  console.log(`Wrote ${name}.artifact.ts (${abi.length} ABI entries, ${bin.length / 2} bytes).`);
}
build("QoreVest", "qoreVest");
build("MockCrossVm", "mockCrossVm");
