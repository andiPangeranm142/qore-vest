/**
 * gen-evidence.mjs - generate src/evidence.ts from deployments/usage.json
 * (written by scripts/usage.ts), so the demo page can show the verified
 * on-chain evidence with explorer links.
 *
 * If usage.json does not exist yet (the usage run has not happened), it
 * writes a module with an empty evidence list instead of failing the build.
 *
 * Run: node scripts/gen-evidence.mjs (also runs as the `prebuild` step).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const usagePath = path.resolve(dir, "..", "deployments", "usage.json");
const outPath = path.resolve(dir, "..", "src", "evidence.ts");

let usage = null;
try {
  usage = JSON.parse(fs.readFileSync(usagePath, "utf8"));
} catch {
  // No usage run yet — the page renders without the evidence section.
}

const header = `/**
 * evidence.ts - GENERATED by scripts/gen-evidence.mjs from
 * deployments/usage.json. Do not edit by hand; re-run the generator.
 *
 * The verified on-chain evidence of the atomic EVM→Native vesting flow:
 * every schedule creation, claim, and forced revert from the usage run,
 * with both the EVM and the Cosmos transaction hashes.
 */

export type EvidenceStep = {
  action: string;
  beneficiary?: string;
  amount?: string;
  amountQvest?: string;
  amountBaseUnits?: string;
  start?: number;
  cliff?: number;
  duration?: number;
  status?: string;
  note?: string;
  claimedTotal?: string;
  qvestBalance?: string;
  nativeAllowance?: string;
  invariantHolds?: boolean;
  stateUnchanged?: boolean;
  evmTx?: string;
  cosmosTx?: string;
};

export type UsageEvidence = {
  contract: string;
  contractNativeAddress: string;
  nativeTarget: string;
  steps: EvidenceStep[];
  finalVerification: Record<string, unknown>;
  ranAt: string;
} | null;

`;

if (!usage) {
  fs.writeFileSync(outPath, header + "export const USAGE_EVIDENCE: UsageEvidence = null;\n");
  console.log("gen-evidence: no deployments/usage.json yet; wrote an empty evidence module.");
  process.exit(0);
}

const evidence = {
  contract: usage.contract,
  contractNativeAddress: usage.contractNativeAddress,
  nativeTarget: usage.nativeTarget,
  steps: usage.steps,
  finalVerification: usage.finalVerification,
  ranAt: usage.ranAt,
};
fs.writeFileSync(
  outPath,
  header + `export const USAGE_EVIDENCE: UsageEvidence = ${JSON.stringify(evidence, null, 2)};\n`,
);
console.log(`gen-evidence: wrote src/evidence.ts (${usage.steps.length} steps).`);
